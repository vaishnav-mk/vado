// Regenerates src/replication/colos.js: each Cloudflare colo's city and coordinates, for maps and labels.
//   node scripts/colos.mjs
import { writeFile } from "node:fs/promises";

const res = await fetch("https://speed.cloudflare.com/locations", { headers: { referer: "https://speed.cloudflare.com/" } });
if (!res.ok) throw new Error(`speed.cloudflare.com/locations answered ${res.status}`);
const list = (await res.json()).sort((a, b) => a.iata.localeCompare(b.iata));
const rows = list.map((c) => `  ${c.iata}: [${JSON.stringify(c.city)}, ${+c.lat.toFixed(2)}, ${+c.lon.toFixed(2)}],`);
await writeFile(new URL("../src/replication/colos.js", import.meta.url), `// Generated by scripts/colos.mjs from https://speed.cloudflare.com/locations. Do not edit.
/** Cloudflare colo (IATA code) -> [city, latitude, longitude]. */
export const COLOS = {
${rows.join("\n")}
};
`);
console.log(`${list.length} colos`);
